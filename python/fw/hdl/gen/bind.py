"""``gen_bind``: the bind module that feeds a design's monitors (K10.3).

    sv_tb   = gen_tb(r, s, top_module="chain", bind=True)   # adds mon_<port>
    sv_bind = gen_bind(r, s, top_module="chain")

returns the text of one file with

- module ``<top>_fw_mon``: input ports only, one per pin of each protocol
  port of the DUT (named as the DUT's pin, ``in_valid``), each fed into an
  RTL -> class ``fw_pin_bridge`` at ``top.mon_<port>_pins.<pin path>``: the
  pins of the ``fw_monitor`` bundle ``gen_tb(..., bind=True)`` adds beside
  the monitor ``mon_<port>``. A monitor bundle's signals are all inputs of
  the class top, so each bridge only samples its pin; its ``o`` is left
  open and nothing drives a DUT net.
- ``bind <top> <top>_fw_mon u_fw_mon (.<pin>(<pin>), ...);``: the DUT's
  nets are its ports (the emitter's names: the member path joined with
  ``_``).

The bound module observes the DUT wherever it is instantiated; the class
it feeds is the one elaborated as ``top`` (``<top>_tb``'s).
"""
from __future__ import annotations

from typing import List, Optional

from .tb import _find_xtor, _ports, _targ, _vtype
from .kit import GenError


def gen_bind(r, scan, top_module: Optional[str] = None, *, inst: str = "u_fw_mon") -> str:
    """The bind module SV of elaborated design ``r`` whose emitted module is
    ``top_module`` (default: the IR top's name). ``scan`` is checked for a
    monitor per protocol port (as ``gen_tb(..., bind=True)`` adds);
    ``inst`` names the bound instance."""
    ctxt, top = r.to_ir()
    dut = top_module or top
    _, bundles = _ports(r)
    ports: List[str] = []
    bridges: List[str] = []
    conns: List[str] = []
    for b in bundles:
        if _find_xtor(scan, b, "monitor") is None:
            raise GenError("FW-E-TB-MON", f"{b.path}: no monitor for {b.btype_name} in the scan")
        port = "_".join(b.rel_path(r.top))
        for s in b.leaves():
            rel = s.rel_path(b)
            leaf = "_".join(s.rel_path(r.top))
            path = ".".join(["top", f"mon_{port}_pins"] + rel)
            ports.append(f"    input {_vtype(s.width)} {leaf}")
            bridges.append(f"    fw_pin_bridge #({_targ(s.type_name)}, \"{path}\") b_{leaf}(.i({leaf}), .o());")
            conns.append(f".{leaf}({leaf})")
    L = [f"// Generated by fw.hdl.gen.bind for {dut}. Do not edit.",
         f"// Feeds {dut}'s pins to the monitors of {dut}_tb_c (gen_tb bind=True);",
         "// samples only: every port is an input.",
         f"module {dut}_fw_mon ("]
    L += [f"{p}{',' if i < len(ports) - 1 else ''}" for i, p in enumerate(ports)]
    L += [");"]
    L += bridges
    L += ["endmodule", "",
          f"bind {dut} {dut}_fw_mon {inst} ({', '.join(conns)});", ""]
    return "\n".join(L)
