"""fe-sv's fw_hdl_pkg: the spec's API declarations with generated bodies.

The spec (``fw-hdl-spec/bindings/sv``) is declarations only: every method is
an ``extern`` prototype. A tool supplies its own package with a body for
each (core-layer1.md §4.1). fe-sv never executes those bodies -- its
interpreter replaces every API method with an intrinsic (:mod:`.rt`) -- so
the bodies it generates only make the package compile: a void method is
empty, any other returns a default value. They are generated from the
spec's declarations each time the API is loaded, so they follow the spec.

The generated file, ``fw_fe_sv_bodies.svh``, goes in a cache directory that
is searched before fe-sv's own ``share/sv`` (macros, package) and the spec's
``bindings/sv`` (the declarations).
"""
from __future__ import annotations

import hashlib
import os
import re
import tempfile
from pathlib import Path
from typing import List, Optional

import pyslang
from pyslang import syntax

SHARE_SV = Path(__file__).parent / "share" / "sv"
API_PACKAGE = "fw_hdl_pkg"
BODIES_FILE = "fw_fe_sv_bodies.svh"


class ApiError(Exception):
    pass


def spec_dir(path: Optional[str] = None) -> Path:
    """The fw-hdl-spec checkout: ``path``, else ``$FW_HDL_SPEC``, else
    ``$IVPM_PACKAGES/fw-hdl-spec``."""
    cands = [path, os.environ.get("FW_HDL_SPEC")]
    if os.environ.get("IVPM_PACKAGES"):
        cands.append(os.path.join(os.environ["IVPM_PACKAGES"], "fw-hdl-spec"))
    for c in cands:
        if c and (Path(c) / "bindings" / "sv" / "fw_hdl_api.svh").is_file():
            return Path(c)
    raise ApiError("fw-hdl-spec not found: pass spec_dir, or set FW_HDL_SPEC")


def _text(node) -> str:
    """Source text of a syntax node, comments dropped, whitespace collapsed."""
    s = str(node)
    s = re.sub(r"//[^\n]*", "", s)
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return " ".join(s.split())


def _classes(root):
    out = []

    def walk(n):
        if n.kind == syntax.SyntaxKind.ClassDeclaration:
            out.append(n)
            return
        for c in n:
            if isinstance(c, syntax.SyntaxNode):
                walk(c)
    walk(root)
    return out


def _local_names(cls) -> set:
    """Names a class declares that an out-of-block return type must qualify:
    its parameters and typedefs."""
    names = set()
    if cls.parameters is not None:
        for d in cls.parameters.declarations:
            for dd in getattr(d, "declarators", ()):
                if hasattr(dd, "name"):
                    names.add(dd.name.valueText)
    for it in cls.items:
        d = getattr(it, "declaration", it)
        if d.kind == syntax.SyntaxKind.TypedefDeclaration:
            names.add(d.name.valueText)
    return names


def _port_list(proto) -> str:
    """The arguments as an out-of-block body repeats them: no defaults."""
    if proto.portList is None:
        return "()"
    args = []
    for p in proto.portList.ports:
        if not isinstance(p, syntax.FunctionPortSyntax):
            continue
        d = p.declarator
        t = " ".join(x for x in (_text(p.direction) if p.direction else "",
                                 _text(p.dataType) if p.dataType else "") if x)
        dims = "".join(_text(x) for x in d.dimensions)
        args.append(" ".join(x for x in (t, d.name.valueText) if x) + (" " + dims if dims else ""))
    return "(" + ", ".join(args) + ")"


def generate_bodies(spec: Path, externs: Optional[set] = None) -> str:
    """Out-of-block default bodies for every extern method of the API. Adds
    each ``(class, method)`` to ``externs`` if given."""
    sv = spec / "bindings" / "sv"
    sm = pyslang.SourceManager()
    sm.addUserDirectories(str(sv))
    pp = pyslang.parsing.PreprocessorOptions()
    pp.additionalIncludePaths = [str(sv)]
    bag = pyslang.Bag()
    bag.preprocessorOptions = pp
    tree = syntax.SyntaxTree.fromFile(str(sv / "fw_hdl_pkg.sv"), sm, bag)
    lines = ["// Generated by fw-hdl-fe-sv from the fw-hdl-spec API. Do not edit.",
             "// Never executed: fe-sv runs an intrinsic for every API method.", ""]
    for cls in _classes(tree.root):
        if _text(cls.virtualOrInterface) == "interface":
            continue
        cname = cls.name.valueText
        local = _local_names(cls)
        for it in cls.items:
            if it.kind != syntax.SyntaxKind.ClassMethodPrototype:
                continue
            quals = [q.valueText for q in it.qualifiers]
            if "extern" not in quals:
                continue
            proto = it.prototype
            name = _text(proto.name)
            if externs is not None:
                externs.add((cname, name))
            args = _port_list(proto)
            if proto.keyword.valueText == "task":
                lines.append(f"task {cname}::{name}{args}; endtask")
                continue
            ret = _text(proto.returnType)
            if ret == "void":
                lines.append(f"function void {cname}::{name}{args}; endfunction")
                continue
            qret = f"{cname}::{ret}" if ret in local else ret
            lines.append(f"function {qret} {cname}::{name}{args}; "
                         f"{qret} __r; return __r; endfunction")
    return "\n".join(lines) + "\n"


class Api:
    """The API as fe-sv compiles it: files and include directories."""

    def __init__(self, spec: Optional[str] = None, cache_dir: Optional[str] = None):
        self.spec = spec_dir(spec)
        self.extern_methods: set = set()
        text = generate_bodies(self.spec, self.extern_methods)
        if cache_dir is None:
            key = hashlib.sha1(text.encode()).hexdigest()[:12]
            cache_dir = os.path.join(tempfile.gettempdir(), f"fw-hdl-fe-sv-{key}")
        os.makedirs(cache_dir, exist_ok=True)
        path = Path(cache_dir) / BODIES_FILE
        if not path.is_file() or path.read_text() != text:
            path.write_text(text)
        self.bodies_dir = Path(cache_dir)

    @property
    def incdirs(self) -> List[str]:
        """fe-sv's directories first, so its macros and package win."""
        return [str(self.bodies_dir), str(SHARE_SV), str(self.spec / "bindings" / "sv")]

    @property
    def files(self) -> List[str]:
        return [str(SHARE_SV / "fw_hdl_pkg.sv")]
